"use strict";

// TERRA résumé: a one-page record of your field work to print, save as PDF or copy.
// Built only from your own local data. It never includes locations, notes or photos, and
// says plainly what is self-reported and what isn't verified.
const TerraResume = (() => {
  const unknown = n => typeof n !== "string" || !n.trim() || n.trim().toLowerCase() === "unknown";
  const GROUPS = { plant: "plants", fungus: "fungi", insect: "insects", mammal: "mammals", bird: "birds", fish: "fish", reptile: "reptiles & amphibians", other: "other organisms" };

  // Pure: the résumé's content. profile: { name, bio, credentials }.
  function build({ profile, records, projects, p, achievements = [], rares = [], matches = () => true, today }) {
    const active = records.filter(r => !r.deletedAt);
    const dates = active.map(r => r.date).sort();
    const species = new Map(), keyOf = (typeof TerraXP !== "undefined" ? TerraXP : require("./xp.js")).speciesKey(active);
    for (const r of active) {
      const key = keyOf(r);
      if (!key) continue;
      const prev = species.get(key);
      species.set(key, { name: prev?.name ?? (unknown(r.name) ? r.taxon.scientificName : r.name.trim()), scientific: prev?.scientific || r.taxon?.scientificName || "", count: (prev?.count ?? 0) + 1 });
    }
    const groups = Object.entries(GROUPS).map(([id, label]) => ({ label, count: active.filter(r => r.type === id).length, species: new Set(active.filter(r => r.type === id).map(keyOf).filter(Boolean)).size }))
      .filter(g => g.count).sort((a, b) => b.count - a.count);
    const byId = new Map(active.map(r => [r.id, r]));
    const completed = projects.filter(pr => pr.complete).map(pr => ({ title: pr.title, start: pr.date || "", end: pr.endDate || pr.date || "", records: pr.observationIds.filter(id => byId.has(id) && matches(pr, byId.get(id))).length }));
    const identified = active.filter(r => r.taxon).length;
    return {
      name: profile.name, bio: profile.bio?.trim() ?? "", credentials: profile.credentials?.trim() ?? "", generated: today,
      headline: `${p.xp.name} field naturalist · Level ${p.xp.level} · ${p.xp.xp} field XP`,
      stats: [
        ["Observations", active.length], ["Species", species.size], ["Field days", new Set(dates).size],
        ["Longest streak", `${p.streak.longest} day${p.streak.longest === 1 ? "" : "s"}`], ["Scientific names", `${active.length ? Math.round(identified / active.length * 100) : 0}%`],
        ["Active", dates.length ? `${dates[0]} – ${dates[dates.length - 1]}` : "–"]
      ],
      groups, top: [...species.values()].sort((a, b) => b.count - a.count || a.name.localeCompare(b.name)).slice(0, 8),
      projects: completed,
      review: { tier: p.standing.tier.name, reviews: p.review.reviews, accuracy: p.review.reviews ? Math.round(p.review.accuracy * 100) : null, weight: p.standing.weight },
      achievements, rares: rares.filter(r => r.seen).map(r => r.name)
    };
  }

  function text(r) {
    const lines = [r.name, r.headline];
    if (r.credentials) lines.push(`Credentials (self-described): ${r.credentials}`);
    if (r.bio) lines.push("", r.bio);
    lines.push("", "FIELD RECORD", ...r.stats.map(([k, v]) => `- ${k}: ${v}`));
    if (r.groups.length) lines.push("", "EXPERIENCE BY GROUP", ...r.groups.map(g => `- ${g.label}: ${g.count} observation${g.count === 1 ? "" : "s"}, ${g.species} species`));
    if (r.top.length) lines.push("", "MOST OBSERVED", ...r.top.map(t => `- ${t.name}${t.scientific && t.scientific !== t.name ? ` (${t.scientific})` : ""} × ${t.count}`));
    if (r.projects.length) lines.push("", "COMPLETED PROJECTS", ...r.projects.map(pr => `- ${pr.title}${pr.start ? ` (${pr.start}${pr.end && pr.end !== pr.start ? ` – ${pr.end}` : ""})` : ""}: ${pr.records} record${pr.records === 1 ? "" : "s"}`));
    lines.push("", "IDENTIFICATION REVIEW", `- ${r.review.tier}${r.review.reviews ? `: ${r.review.reviews} practice reviews, ${r.review.accuracy}% right` : ""}`);
    if (r.achievements.length) lines.push("", "ACHIEVEMENTS", `- ${r.achievements.join(", ")}`);
    if (r.rares.length) lines.push(`- Rare sightings in the TERRA terrarium: ${r.rares.join(", ")}`);
    lines.push("", `Generated by TERRA on ${r.generated} from the observer's own local journal. Observations are self-reported; names are the observer's identifications and are not yet community- or expert-verified. Locations are not included.`);
    return lines.join("\n");
  }

  const el = (tag, cls, t) => { const e = document.createElement(tag); if (cls) e.className = cls; if (t !== undefined) e.textContent = t; return e; };
  function render(root, r, avatar) {
    root.replaceChildren();
    const head = el("header", "resume-head");
    if (avatar) head.append(avatar);
    const who = el("div");
    who.append(el("h2", "resume-name", r.name), el("p", "resume-headline", r.headline));
    if (r.credentials) who.append(el("p", "resume-credentials", `Credentials (self-described): ${r.credentials}`));
    head.append(who);
    root.append(head);
    if (r.bio) root.append(el("p", "resume-bio", r.bio));
    const section = (title, body) => { const s = el("section", "resume-section"); s.append(el("h3", "", title), body); root.append(s); };
    const stats = el("dl", "resume-stats");
    for (const [k, v] of r.stats) stats.append(el("dt", "", k), el("dd", "", String(v)));
    section("Field record", stats);
    if (r.groups.length) { const ul = el("ul"); for (const g of r.groups) ul.append(el("li", "", `${g.label[0].toUpperCase()}${g.label.slice(1)}: ${g.count} observation${g.count === 1 ? "" : "s"}, ${g.species} species`)); section("Experience by group", ul); }
    if (r.top.length) { const ol = el("ol", "resume-species"); for (const t of r.top) { const li = el("li"); li.append(el("span", "", t.name)); if (t.scientific && t.scientific !== t.name) li.append(el("em", "", ` ${t.scientific}`)); li.append(el("small", "", ` × ${t.count}`)); ol.append(li); } section("Most observed", ol); }
    if (r.projects.length) { const ul = el("ul"); for (const pr of r.projects) ul.append(el("li", "", `${pr.title}${pr.start ? ` (${pr.start}${pr.end && pr.end !== pr.start ? ` – ${pr.end}` : ""})` : ""}: ${pr.records} record${pr.records === 1 ? "" : "s"}`)); section("Completed projects", ul); }
    section("Identification review", el("p", "", `${r.review.tier}${r.review.reviews ? `. ${r.review.reviews} practice reviews, ${r.review.accuracy}% right${r.review.weight ? `, vote weight ${r.review.weight}×` : ""}.` : ". No reviews yet."}`));
    if (r.achievements.length || r.rares.length) {
      const p = el("p", "", [r.achievements.length ? `Achievements: ${r.achievements.join(", ")}.` : "", r.rares.length ? `Rare sightings: ${r.rares.join(", ")}.` : ""].filter(Boolean).join(" "));
      section("Achievements", p);
    }
    root.append(el("p", "resume-footer", `Generated by TERRA on ${r.generated} from the observer's own local journal. Observations are self-reported; names are the observer's identifications and are not yet community- or expert-verified. Locations are not included.`));
  }
  return Object.freeze({ build, text, render });
})();
if (typeof module !== "undefined") module.exports = TerraResume;
